def get_personalities() -> Dict[str, MBTIPersonality]:
    """获取所有MBTI性格模板"""
    personalities = {}
    for type_code, template in PERSONALITY_TEMPLATES.items():
        full_prompt = _build_base_prompt(MBTIPersonality(type_code=type_code, **template))
        validation_prompt = _build_validation_prompt(MBTIPersonality(type_code=type_code, **template))
        personalities[type_code] = MBTIPersonality(
            type_code=type_code,
            full_prompt=full_prompt,
            validation_prompt=validation_prompt,
            **template
        )
    return personalities


