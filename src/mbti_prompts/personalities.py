"""
16套MBTI性格Prompt模板
每套包含：
1. 性格描述：MBTI维度的语言化定义
2. Few-shot锚定：3-5个示范问答
3. 性格校验问题：5个反问确保不"演过头"
"""

from dataclasses import dataclass
from typing import List, Dict


@dataclass
class MBTIPersonality:
    """单个MBTI性格模板"""
    type_code: str  # e.g., "INTJ"
    name: str       # e.g., "战略家"
    description: str
    few_shot_examples: List[Dict[str, str]]  # [{"Q": ..., "A": ...}]
    validation_questions: List[str]
    core_traits: List[str]
    communication_style: str
    decision_making: str
    conflict_handling: str
    # Computed fields
    full_prompt: str = ""
    validation_prompt: str = ""


# MBTI维度解释
MBTI_DIMENSIONS = {
    "E": "外向 (Extraversion) - 从外部世界获取能量",
    "I": "内向 (Introversion) - 从内部世界获取能量",
    "N": "直觉 (iNtuition) - 关注可能性和未来",
    "S": "实感 (Sensing) - 关注具体事实和当下",
    "T": "思考 (Thinking) - 基于逻辑和分析做决策",
    "F": "情感 (Feeling) - 基于价值观和他人影响做决策",
    "J": "判断 (Judging) - 喜欢结构和确定性",
    "P": "感知 (Perceiving) - 喜欢灵活性和开放选项",
}


def _build_base_prompt(personality: MBTIPersonality) -> str:
    """构建基础Prompt"""
    dims = personality.type_code
    e_i = "E" if "E" in dims else "I"
    n_s = "N" if "N" in dims else "S"
    t_f = "T" if "T" in dims else "F"
    j_p = "J" if "J" in dims else "P"

    prompt = f"""你正在扮演一个{personality.name}（MBTI类型：{personality.type_code}）。

## 你的核心性格特征
{chr(10).join(f"- {trait}" for trait in personality.core_traits)}

## MBTI维度解读
- 能量方向：{MBTI_DIMENSIONS[e_i]}
- 信息收集：{MBTI_DIMENSIONS[n_s]}
- 决策方式：{MBTI_DIMENSIONS[t_f]}
- 生活态度：{MBTI_DIMENSIONS[j_p]}

## 性格描述
{personality.description}

## 沟通风格
{personality.communication_style}

## 决策方式
{personality.decision_making}

## 处理冲突的方式
{personality.conflict_handling}

## Few-shot示例
"""
    for i, example in enumerate(personality.few_shot_examples, 1):
        prompt += f"""
### 示例 {i}
**问题**: {example['Q']}
**回答**: {example['A']}
"""
    prompt += """
## 回答要求
1. 你的回答必须体现上述性格特征
2. 避免过于中立或八面玲珑，要有自己的立场
3. 用第一人称"我"来表达
4. 如果某些观点与你性格不符，明确指出
"""
    return prompt


def _build_validation_prompt(personality: MBTIPersonality) -> str:
    """构建性格校验Prompt"""
    questions = "\n".join(f"- {q}" for q in personality.validation_questions)
    return f"""
## 性格校验
回答以下问题来确认你保持了角色：

{questions}

请诚实回答，如果你发现自己的回答偏离了{personality.type_code}的性格，请调整。
"""


